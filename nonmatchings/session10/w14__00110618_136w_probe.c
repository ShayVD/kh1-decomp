/* 00110618 136w LCS at the right size (1072 vs 1072; best earlier 167), mode hand. New: sched1 pins insns that use/set pseudos not crossing a call into their call interval (sched_before_next_call), so sxd2 = sxd + sxd / syd2 = syd + syd as separate temps; then hill-climbed (tools: calls fixed, matrix stores free only inside their call interval, temps free) - the order is unnatural, treat it as a probe. Left: FP register allocation in the prologue (orig: neg r first, n->f21, fa->f23, d->f20, a->f25; spills w,rn,n2), fb not in a register (orig f24), sched2 moving callee-saved FP divs across calls. */

#include "common.h"
typedef f32 Mtx[4][4] __attribute__((aligned(16)));
void sceVu0UnitMatrix(Mtx);
void sceVu0MulMatrix(Mtx, Mtx, Mtx);
void func_00110618(Mtx m0, Mtx m1, Mtx m2, Mtx m3, Mtx m4, Mtx m5,
                   f32 d, f32 a, f32 px, f32 py, f32 pz, f32 l, f32 r, f32 n, f32 fb, f32 fa) {
    Mtx t;
    f32 w, rn, n2, fan, dfa, dfb, fbn;
    f32 a22, a32, zza, zwa, b22, b32, zzb, zwb;
    f32 sx, sy, sxd, syd, sx2, sy2, sxd2, syd2;
    dfa = fa - n;
    rn = -r * n;
    w = r - l;
    fan = fa * n;
    syd = n * 229.0f / d;
    a32 = (rn + l * fa) / dfa;
    a22 = fan * w / dfa;
    sxd = n * 320.0f / d;
    sceVu0UnitMatrix(m2);
    m2[0][0] = d;
    m2[3][2] = 1.0f;
    m2[2][2] = 0.0f;
    m2[1][1] = d;
    syd2 = syd + syd;
    m2[3][3] = 0.0f;
    n2 = n + n;
    m2[2][3] = 1.0f;
    sxd2 = sxd + sxd;
    dfb = fb - n;
    sceVu0UnitMatrix(t);
    t[2][2] = a22;
    t[3][2] = a32;
    t[3][0] = py;
    fbn = fb * n;
    t[1][1] = px;
    sx = n2 / sxd2;
    t[0][0] = a;
    zza = (fa + n) / dfa;
    t[3][1] = pz;
    sceVu0MulMatrix(m2, t, m2);
    sceVu0UnitMatrix(m3);
    zzb = (fb + n) / dfb;
    m3[3][3] = 0.0f;
    b22 = fbn * w / dfb;
    b32 = (rn + l * fb) / dfb;
    m3[2][3] = 1.0f;
    zwa = fan * -2.0f / dfa;
    m3[0][0] = sx;
    sy = n2 / syd2;
    m3[3][2] = zwa;
    m3[1][1] = sy;
    m3[2][2] = zza;
    sceVu0UnitMatrix(m0);
    sx2 = n * 2045.0f / d;
    sy2 = n * 360.5f / d;
    m0[0][0] = d;
    m0[2][2] = 0.0f;
    m0[3][2] = 1.0f;
    m0[2][3] = 1.0f;
    m0[3][3] = 0.0f;
    m0[1][1] = d;
    sceVu0UnitMatrix(t);
    t[2][2] = b22;
    t[3][2] = b32;
    t[1][1] = px;
    t[0][0] = a;
    t[3][0] = py;
    t[3][1] = pz;
    sceVu0MulMatrix(m0, t, m0);
    sceVu0UnitMatrix(m1);
    zwb = fbn * -2.0f / dfb;
    m1[2][2] = zzb;
    m1[2][3] = 1.0f;
    m1[3][3] = 0.0f;
    m1[0][0] = sx;
    m1[3][2] = zwb;
    m1[1][1] = sy;
    sceVu0UnitMatrix(m4);
    m4[0][0] = n2 / (sx2 + sx2);
    m4[3][2] = zwb;
    m4[2][3] = 1.0f;
    m4[1][1] = n2 / (sy2 + sy2);
    m4[3][3] = 0.0f;
    m4[2][2] = zzb;
    sceVu0UnitMatrix(m5);
    m5[0][0] = a * d * sx2 / n;
    m5[3][1] = pz;
    m5[3][2] = (r + l) * 0.5f;
    m5[3][3] = 1.0f;
    m5[1][1] = d * px * sy2 / n;
    m5[2][2] = (l - r) * 0.5f;
    m5[3][0] = py;
}
