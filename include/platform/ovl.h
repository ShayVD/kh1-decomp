/* Platform wrapper: the EE overlays. See docs/portability.md and docs/native-overlays.md.
 *
 * On the PS2 the game loads an overlay's MIPS code from KINGDOM.IMG into the overlay area
 * (D_00F20000) with src/io/discfile.c's loader and calls its first byte.  A port cannot run
 * those bytes, so it links the overlays' decompiled C (ovl/NAME/) as native modules instead:
 * PlatOvlLoaded tells the platform which file the loader just read and where, and the
 * platform's answer to a call of D_00F20000 (host/null/main.c's fault redirect,
 * host/vita/main.c's kh1_ovl_entry) asks PlatOvlCall first.
 *
 * On the matching PS2 build PlatOvlLoaded is nothing (no code). */
#ifndef KH1_PLATFORM_OVL_H
#define KH1_PLATFORM_OVL_H

#include "common.h"

#ifdef KH1_PS2
#define PlatOvlLoaded(name, buf, size) ((void)0)
#else
/* the loader read `size` bytes of file `name` to `buf` (discfile.c func_00120678, before the
 * load's callback runs): when buf is the overlay area and a native module of that name is
 * linked and the bytes are its pinned file, that module becomes the current overlay and its
 * data's pointers are fixed up (host/port/ovl.c) */
void PlatOvlLoaded(const char *name, void *buf, s32 size);
/* a call of the overlay entry: 1 and *ret set when the current overlay is native, else 0 */
int PlatOvlCall(int cmd, int arg, int *ret);
/* the current native overlay's name, or 0 */
const char *PlatOvlCurrent(void);

/* the native modules, generated by tools/host/ovlnative.py from ovl/overlays.tsv, ovl/NAME/layout.tsv
 * and ovl/NAME/relocs.tsv: an overlay is linked when every function of its layout has C */
typedef struct {
    u32 at;     /* PS2 address of the data word */
    u32 target; /* the PS2 address it holds */
    void *func; /* the native function at target, or 0 for a data address */
} KH1OvlFix;
typedef struct {
    const char *file; /* the file name the loader is given ("dktitle.x") */
    u32 size;
    const char *sha256;
    int (*entry)(int cmd, int arg); /* the C of the overlay's first function */
    const KH1OvlFix *fix;
    int nfix;
} KH1OvlModule;
extern const KH1OvlModule kh1_ovl_modules[];
extern const int kh1_ovl_module_count;
#endif

#endif /* KH1_PLATFORM_OVL_H */
