#!/usr/bin/env python3
"""The English patch's data changes as a table for the port (docs/english-patch.md).

    python3 -I tools/host/en_ranges.py SLPS_251.98 ENGLISH_SLPS_251.98 > host/port/lang_en.h

Compares the retail ELF (kh1.toml target) with the English patch's (kh1.toml [english]) over the
data, 0x272C70-0x494080, and writes each changed run as (piece, offset, ELF file offset, length):
host/port/lang.c copies those bytes from the disc's own ELF into the data pieces at boot.  Runs
are cut at piece ends; bytes outside the pieces (compiled rodata: timer.c's "/") are left to the
C (lang.h's KH1_EN), and a piece's relocation words are never touched.  The table holds addresses
and lengths only, no bytes of either ELF."""
import hashlib
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import kh1tool as K  # noqa: E402
sys.path.insert(0, os.path.join(ROOT, "tools", "shift"))
import cut_pieces  # noqa: E402

DATA_LO, DATA_HI = 0x272C70, 0x494080
FILE_DELTA = 0x100000 - 0x80   # the ELF's one segment: vaddr - file offset


def pieces():
    """(start, end, name) of every PIECE, and the addresses of their relocation words."""
    import glob
    import re
    out, words = [], set()
    for f in sorted(glob.glob(os.path.join(ROOT, "src", "data", "data_*.s"))):
        cur = None
        off = 0
        for ln in open(f):
            m = cut_pieces.PIECE_RE.match(ln)
            if m:
                a = int(m.group(1), 16)
                out.append((a, a + int(m.group(2), 0), "D_" + m.group(1)))
                cur, off = (a if "PIECE_BEGIN" in ln else None), 0
                continue
            if cur is None:
                continue
            mb = re.match(r"\s*PIECE_BYTES\s+\w+,\s*(\w+),\s*(\w+)", ln)
            if mb:
                off = int(mb.group(1), 0) + int(mb.group(2), 0)
            elif re.match(r"\s*\.word\b", ln):
                words.update(range(cur + off, cur + off + 4))
                off += 4
            elif re.match(r"\s*PIECE_END", ln):
                cur = None
    return sorted(out), words


def main():
    ja, en = (open(p, "rb").read() for p in sys.argv[1:3])
    cfg = K.load_config()
    assert hashlib.sha256(ja).hexdigest() == cfg["target"]["sha256"], "not the retail ELF"
    en_sha = hashlib.sha256(en).hexdigest()
    assert en_sha == cfg["english"]["sha256"], "not the English patch's ELF"
    ps, words = pieces()
    rows, outside = [], 0
    for start, end, name in ps:
        lo, hi = max(start, DATA_LO), min(end, DATA_HI)
        a = lo
        while a < hi:
            if ja[a - FILE_DELTA] == en[a - FILE_DELTA]:
                a += 1
                continue
            assert a not in words, "a relocation word changed at %#x" % a
            b = a + 1
            # run on through unchanged bytes (the same in both) up to the next relocation word
            last = a
            while b < hi and b not in words and b - last < 16:
                if ja[b - FILE_DELTA] != en[b - FILE_DELTA]:
                    last = b
                b += 1
            rows.append((name, a - start, a - FILE_DELTA, last + 1 - a))
            a = last + 1
    covered = {r[2] + i for r in rows for i in range(r[3])}
    for a in range(DATA_LO, DATA_HI):
        if ja[a - FILE_DELTA] != en[a - FILE_DELTA] and a - FILE_DELTA not in covered:
            outside += 1
    names = sorted({r[0] for r in rows})
    print("/* Generated by tools/host/en_ranges.py: the English patch's data runs (docs/english-patch.md).")
    print(" * %d runs, %d bytes, in %d pieces; %d changed bytes outside the pieces are lang.h's (C). */"
          % (len(rows), sum(r[3] for r in rows), len(names), outside))
    print('#define KH1_EN_ELF_SHA256 "%s"' % en_sha)
    print("#define KH1_EN_ELF_SIZE %d" % len(en))
    for n in names:
        print("extern u8 %s[];" % n)
    print("static const struct { u8 *piece; u32 off, at, len; } kh1_en_runs[] = {")
    for name, off, at, n in rows:
        print("    {%s, 0x%x, 0x%x, %d}," % (name, off, at, n))
    print("};")


if __name__ == "__main__":
    main()
